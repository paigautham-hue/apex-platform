#!/usr/bin/env node
/**
 * check-map-orphans.mjs — APEX
 *
 * Purpose: when a branch ADDS new source files under client/src,
 * server, drizzle, or shared, fail unless every new file is mentioned
 * in at least one subsystem map under docs/maps/. New code without
 * a map entry is invisible to the next reader; the maps are supposed
 * to be the complete index.
 *
 * Adapted from Meridian's same-named script.
 *
 * Usage:
 *   node scripts/check-map-orphans.mjs           # check NEW files (PR mode, default)
 *   node scripts/check-map-orphans.mjs --audit   # scan EVERY source file (one-shot)
 *   node scripts/check-map-orphans.mjs --json    # machine-readable output
 *
 * Exit codes:
 *   0 — pass / audit mode / on main
 *   1 — orphans found in PR mode
 *
 * Bypass (for genuine emergencies; document in the PR body):
 *   - SKIP_MAPS_LINT=1 git push      (env var; this script only)
 *   - git push --no-verify           (skip ALL pre-push hooks)
 */

import { execSync } from "node:child_process";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";

const REPO = process.cwd();
const MAPS_DIR = join(REPO, "docs", "maps");

const SOURCE_DIR_PREFIXES = [
  "client/src/",
  "server/",
  "drizzle/",
  "shared/",
];
const SOURCE_EXTENSIONS = new Set([".ts", ".tsx", ".js", ".mjs"]);

const EXCLUDE_PATTERNS = [
  // Tests
  /\.(test|spec)\.(ts|tsx|js|mjs)$/,
  // Type declarations
  /\.d\.ts$/,
  // Build artefacts
  /^client\/dist\//,
  /^dist\//,
  /^build\//,
  // Tooling scripts (intentionally unmapped)
  /^scripts\//,
  // Drizzle raw SQL migrations + meta (auto-generated by drizzle-kit)
  /^drizzle\/\d+_.*\.sql$/,
  /^drizzle\/meta\//,
  /^drizzle\/migrations\//,
  // Entry points implicitly depended on by every map
  /^client\/src\/main\.tsx$/,
  /^client\/src\/vite-env\.d\.ts$/,
  // shadcn/ui primitives — referenced from shell-layout.md collectively
  /^client\/src\/components\/ui\//,
  // Manus-generated version stamps + public assets
  /^client\/public\//,
];

// ── Helpers ──────────────────────────────────────────────────────────────

function sh(cmd) {
  try {
    return execSync(cmd, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

function isBranchMain() {
  return sh("git rev-parse --abbrev-ref HEAD") === "main";
}

function getNewFilesInBranch() {
  const candidates = [
    "git diff --name-only --diff-filter=A origin/main...HEAD",
    "git diff --name-only --diff-filter=A @{upstream}...HEAD",
  ];
  for (const cmd of candidates) {
    const out = sh(cmd);
    if (out) return out.split("\n").filter(Boolean);
  }
  return [];
}

function listAllSourceFiles() {
  const files = [];
  for (const prefix of SOURCE_DIR_PREFIXES) {
    walkDir(join(REPO, prefix), files);
  }
  return files
    .map((p) => relative(REPO, p).replaceAll("\\", "/"))
    .filter((p) => SOURCE_EXTENSIONS.has(getExt(p)));
}

function walkDir(dir, out) {
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const name of entries) {
    if (name === "node_modules" || name === ".git") continue;
    const full = join(dir, name);
    let stat;
    try {
      stat = statSync(full);
    } catch {
      continue;
    }
    if (stat.isDirectory()) walkDir(full, out);
    else if (stat.isFile()) out.push(full);
  }
}

function getExt(path) {
  const dot = path.lastIndexOf(".");
  return dot === -1 ? "" : path.slice(dot);
}

function isExcluded(path) {
  if (!SOURCE_DIR_PREFIXES.some((p) => path.startsWith(p))) return true;
  if (!SOURCE_EXTENSIONS.has(getExt(path))) return true;
  return EXCLUDE_PATTERNS.some((re) => re.test(path));
}

function loadAllMaps() {
  const map = new Map();
  let entries;
  try {
    entries = readdirSync(MAPS_DIR);
  } catch {
    return map;
  }
  for (const name of entries) {
    if (name.startsWith("_")) continue;
    if (!name.endsWith(".md")) continue;
    try {
      const content = readFileSync(join(MAPS_DIR, name), "utf8");
      map.set(name, content);
    } catch {
      // unreadable
    }
  }
  return map;
}

function isMentionedInAnyMap(filePath, mapsByName) {
  const needles = [`\`${filePath}\``, filePath];
  for (const content of mapsByName.values()) {
    for (const needle of needles) {
      if (content.includes(needle)) return true;
    }
  }
  return false;
}

// ── Main ─────────────────────────────────────────────────────────────────

const args = new Set(process.argv.slice(2));
const isAudit = args.has("--audit");
const isJson = args.has("--json");

if (process.env.SKIP_MAPS_LINT === "1") {
  if (!isJson) process.stdout.write("[check-map-orphans] SKIP_MAPS_LINT=1 — skipping\n");
  process.exit(0);
}

if (isBranchMain() && !isAudit) {
  if (!isJson)
    process.stdout.write("[check-map-orphans] on main — orphan check is per-PR, skipping\n");
  process.exit(0);
}

const filesToCheck = isAudit ? listAllSourceFiles() : getNewFilesInBranch();
const inScope = filesToCheck.filter((f) => !isExcluded(f));

if (inScope.length === 0) {
  if (!isJson)
    process.stdout.write(
      `[check-map-orphans] ✓ no new in-scope files to check (${filesToCheck.length} total)\n`,
    );
  process.exit(0);
}

const maps = loadAllMaps();
if (maps.size === 0) {
  process.stderr.write(
    "[check-map-orphans] ⚠️  no maps found under docs/maps/ — bootstrap not yet complete\n",
  );
  process.exit(0);
}

const orphans = inScope.filter((f) => !isMentionedInAnyMap(f, maps));

if (isJson) {
  process.stdout.write(
    JSON.stringify({ checked: inScope.length, orphans, mode: isAudit ? "audit" : "pr" }, null, 2) + "\n",
  );
  process.exit(orphans.length > 0 && !isAudit ? 1 : 0);
}

if (orphans.length === 0) {
  process.stdout.write(
    `[check-map-orphans] ✓ ${inScope.length} ${isAudit ? "source files audited" : "new files in branch"}; all are in some map\n`,
  );
  process.exit(0);
}

const lines = [];
lines.push("");
lines.push(
  isAudit
    ? `[check-map-orphans] ⚠️  ${orphans.length} orphan file(s) found:`
    : `[check-map-orphans] ❌ ${orphans.length} new file(s) in this branch are not in any subsystem map:`,
);
lines.push("");
for (const orphan of orphans) {
  lines.push(`  - ${orphan}`);
}
lines.push("");
lines.push(
  "Each new source file must be added to its subsystem map's Files inventory",
);
lines.push("(docs/maps/*.md). The maps are the codebase index — every source file");
lines.push("should be findable from a map. See docs/MASTER_PLAN.md §9 and");
lines.push("CLAUDE.md for the MAPS-first workflow.");
lines.push("");
lines.push("To bypass for a genuine emergency (document the reason in the PR body):");
lines.push("  SKIP_MAPS_LINT=1 git push");
lines.push("  git push --no-verify   (skip ALL pre-push hooks)");
lines.push("");

process.stderr.write(lines.join("\n"));
process.exit(isAudit ? 0 : 1);
